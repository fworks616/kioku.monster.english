#!/usr/bin/env python3
"""Build reviewed vocabulary details and resumable, text-checked MP3 recordings.

Usage: .venv/bin/python scripts/enrich_pre1.py {prepare,audio,verify,all}
Only public pronunciation data and the English learning text leave the computer.
"""
import argparse
import asyncio
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
from pathlib import Path
import re
import subprocess
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
CACHE = ROOT / '.cache' / 'pre1-enrichment'
DATA = ROOT / 'scripts' / 'data'
DETAILS = ROOT / 'dist' / 'pre1-details.js'
AUDIO = ROOT / 'dist' / 'audio'
VOICE = 'en-US-AriaNeural'
IPA_URL = 'https://raw.githubusercontent.com/open-dict-data/ipa-dict/master/data/en_US.txt'


def vocabulary():
    result = subprocess.run(
        ['node', '--input-type=module', '-e',
         "import {words} from './dist/words.js'; console.log(JSON.stringify(words))"],
        cwd=ROOT, capture_output=True, text=True, check=True)
    return json.loads(result.stdout)


def fetch(url, path):
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        with urllib.request.urlopen(url, timeout=90) as response:
            payload = response.read()
        temporary = path.with_suffix(path.suffix + '.part')
        temporary.write_bytes(payload)
        temporary.replace(path)
    return path.read_text(encoding='utf-8-sig')


def atomic_json(path, value):
    temporary = path.with_suffix(path.suffix + '.part')
    temporary.write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    temporary.replace(path)


def prepare():
    words = [w for w in vocabulary() if w['deck'] == 'pre1' and int(w['id'][1:]) >= 40]
    rows = {}
    for number, line in enumerate((DATA / 'pre1-examples.tsv').read_text(encoding='utf-8').splitlines(), 1):
        if not line.strip() or line.startswith('#'):
            continue
        fields = line.split('\t')
        if len(fields) != 3:
            raise ValueError('Expected word, example, translation at line %d' % number)
        word, example, translation = fields
        if word in rows:
            raise ValueError('Duplicate example: ' + word)
        if not example.endswith(('.', '!', '?')) or not re.search('[\u3040-\u9fff]', translation):
            raise ValueError('Incomplete example: ' + word)
        rows[word] = (example, translation)
    expected = {w['word'] for w in words}
    if len(words) != 460 or set(rows) != expected:
        raise ValueError('Example coverage: missing=%s extra=%s (%d/460)' %
                         (sorted(expected-set(rows)), sorted(set(rows)-expected), len(rows)))
    pronunciations = {}
    for line in fetch(IPA_URL, CACHE / 'en_US.txt').splitlines():
        if '\t' in line:
            word, ipa = line.split('\t', 1)
            pronunciations[word.lower()] = ipa.split(', ')[0]
    overrides = json.loads((DATA / 'pre1-overrides.json').read_text(encoding='utf-8'))
    enriched = {}
    for word in words:
        spelling = word['word']
        example, translation = rows[spelling]
        detail = {'ipa': pronunciations.get(spelling), 'example': example, 'translation': translation}
        detail.update(overrides.get(spelling, {}))
        if not detail['ipa'] or not detail['ipa'].startswith('/') or detail['ipa'] == '/—/':
            raise ValueError('Missing IPA: ' + spelling)
        enriched[spelling] = detail
    content = ('// Generated by scripts/enrich_pre1.py; examples are original.\n'
               '/*\n' + (ROOT / 'THIRD_PARTY_NOTICES.md').read_text(encoding='utf-8') + '\n*/\n'
               'export const pre1Details = ' + json.dumps(enriched, ensure_ascii=False, indent=2) + ';\n')
    temporary = DETAILS.with_suffix('.js.part')
    temporary.write_text(content, encoding='utf-8')
    temporary.replace(DETAILS)
    print('Prepared: 460 original examples, Japanese translations, and US IPA.', flush=True)


def signature(text, rate, context=''):
    return hashlib.sha256((VOICE + '\n' + rate + '\n' + text + '\n' + context).encode()).hexdigest()


def valid_mp3(path):
    if not path.exists() or path.stat().st_size <= 1000:
        return False
    with path.open('rb') as stream:
        head = stream.read(3)
    return head == b'ID3' or (len(head) >= 2 and head[0] == 255 and head[1] & 224 == 224)


async def audio(concurrency):
    import edge_tts
    AUDIO.mkdir(exist_ok=True)
    CACHE.mkdir(parents=True, exist_ok=True)
    stamp_path = AUDIO / 'generation-state.json'
    stamps = json.loads(stamp_path.read_text()) if stamp_path.exists() else {}
    contexts = json.loads((DATA / 'pre1-audio-contexts.json').read_text())
    words = [w for w in vocabulary() if w['deck'] == 'pre1' and int(w['id'][1:]) >= 40]
    if len(words) != 460 or any(w['ipa'] == '—' or 'The word “' in w['example'] for w in words):
        raise ValueError('Run prepare before generating audio; vocabulary is incomplete.')
    jobs = [(w, kind, w['word' if kind == 'word' else 'example'], '+0%' if kind == 'word' else '-5%')
            for w in words for kind in ('word', 'example')]
    pending = []
    for w, kind, text, rate in jobs:
        name = w['id'] + '-' + kind + '.mp3'
        context = contexts.get(text, '') if kind == 'word' else ''
        if not valid_mp3(AUDIO / name) or stamps.get(name) != signature(text, rate, context):
            pending.append((name, text, rate, context))
    print('Audio: %d/920 current; %d to generate.' % (920-len(pending), len(pending)), flush=True)
    sem = asyncio.Semaphore(concurrency)
    completed = 920-len(pending)
    failures = []

    async def render(job):
        nonlocal completed
        name, text, rate, context = job
        async with sem:
            target = AUDIO / name
            temporary = target.with_suffix('.mp3.part')
            for attempt in range(5):
                try:
                    if context:
                        # Isolated heteronyms can be read with the wrong part of
                        # speech. Synthesize a disambiguating sentence, then use
                        # service word timestamps to retain only the target word.
                        source = CACHE / (name + '.context.mp3')
                        boundary = None
                        async def contextual():
                            nonlocal boundary
                            with source.open('wb') as output:
                                async for chunk in edge_tts.Communicate(
                                        context, VOICE, rate=rate, boundary='WordBoundary').stream():
                                    if chunk['type'] == 'audio':
                                        output.write(chunk['data'])
                                    elif chunk['type'] == 'WordBoundary':
                                        token = re.sub(r'[^a-z]', '', chunk['text'].lower())
                                        if token == text.lower():
                                            boundary = chunk
                        await asyncio.wait_for(contextual(), timeout=90)
                        if boundary is None:
                            raise ValueError('Target word timestamp not found')
                        start = max(0, boundary['offset']/10_000_000-0.025)
                        end = (boundary['offset']+boundary['duration'])/10_000_000+0.045
                        process = await asyncio.create_subprocess_exec(
                            'ffmpeg', '-hide_banner', '-loglevel', 'error', '-y',
                            '-i', str(source), '-af',
                            'atrim=start=%.6f:end=%.6f,asetpts=PTS-STARTPTS' % (start, end),
                            '-codec:a', 'libmp3lame', '-b:a', '128k', '-f', 'mp3', str(temporary),
                            stdout=asyncio.subprocess.DEVNULL, stderr=asyncio.subprocess.PIPE)
                        _, stderr = await process.communicate()
                        if process.returncode:
                            raise RuntimeError(stderr.decode())
                    else:
                        await asyncio.wait_for(
                            edge_tts.Communicate(text, VOICE, rate=rate).save(str(temporary)), timeout=90)
                    if not valid_mp3(temporary):
                        raise ValueError('Invalid or empty MP3')
                    temporary.replace(target)
                    stamps[name] = signature(text, rate, context)
                    atomic_json(stamp_path, stamps)
                    completed += 1
                    if completed % 20 == 0 or completed == 920:
                        print('Audio: %d/920' % completed, flush=True)
                    return
                except Exception as exc:
                    if temporary.exists():
                        temporary.unlink()
                    if attempt == 4:
                        failures.append({'file': name, 'error': str(exc)})
                        print('FAILED: %s: %s' % (name, exc), flush=True)
                    else:
                        await asyncio.sleep(min(2 ** (attempt+1), 16))

    await asyncio.gather(*(render(job) for job in pending))
    atomic_json(CACHE / 'audio-failures.json', failures)
    if failures:
        raise RuntimeError('%d recordings failed; rerun to resume.' % len(failures))
    all_words = vocabulary()
    manifest = {'voice': VOICE, 'language': 'en-US', 'wordRate': '+0%', 'exampleRate': '-5%',
                'files': [w['id']+'-'+kind+'.mp3' for w in all_words for kind in ('word', 'example')]}
    atomic_json(AUDIO / 'manifest.json', manifest)
    print('Ready: 1,060 recordings, including 920 new recordings.', flush=True)


def verify(decode=False):
    words = vocabulary()
    added = [w for w in words if w['deck'] == 'pre1' and int(w['id'][1:]) >= 40]
    errors = []
    stamps_path = AUDIO / 'generation-state.json'
    stamps = json.loads(stamps_path.read_text()) if stamps_path.exists() else {}
    contexts = json.loads((DATA / 'pre1-audio-contexts.json').read_text())
    for word in added:
        if word['ipa'] == '—' or 'The word “' in word['example']:
            errors.append('Placeholder: ' + word['id'])
        for kind in ('word', 'example'):
            name = word['id']+'-'+kind+'.mp3'
            text = word['word' if kind == 'word' else 'example']
            rate = '+0%' if kind == 'word' else '-5%'
            context = contexts.get(text, '') if kind == 'word' else ''
            if not valid_mp3(AUDIO / name) or stamps.get(name) != signature(text, rate, context):
                errors.append('Missing or stale audio: '+name)
    manifest = json.loads((AUDIO / 'manifest.json').read_text())
    expected = {w['id']+'-'+kind+'.mp3' for w in words for kind in ('word', 'example')}
    if set(manifest['files']) != expected:
        errors.append('Manifest does not match vocabulary')
    if len(added) != 460 or len(words) != 530:
        errors.append('Incorrect word count')
    if errors:
        raise ValueError('\n'.join(errors[:30])+'\nTotal errors: '+str(len(errors)))
    if decode:
        def decode_file(word):
            for kind in ('word', 'example'):
                path = AUDIO / (word['id']+'-'+kind+'.mp3')
                result = subprocess.run(
                    ['ffmpeg', '-hide_banner', '-v', 'error', '-i', str(path), '-f', 'null', '-'],
                    capture_output=True, text=True, timeout=30)
                if result.returncode or result.stderr.strip():
                    raise ValueError('MP3 decoding failed: %s: %s' % (path.name, result.stderr))
        with ThreadPoolExecutor(max_workers=4) as pool:
            list(pool.map(decode_file, added))
        print('Decoded: all 920 additional MP3s without errors.', flush=True)
    print('Verified: 460 enriched words, 920 matching MP3s, complete 1,060-file manifest.', flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['prepare', 'audio', 'verify', 'all'])
    parser.add_argument('--concurrency', type=int, default=4)
    parser.add_argument('--decode', action='store_true', help='decode all new MP3s with FFmpeg during verification')
    args = parser.parse_args()
    if not 1 <= args.concurrency <= 8:
        parser.error('concurrency must be between 1 and 8')
    if args.action in ('prepare', 'all'):
        prepare()
    if args.action in ('audio', 'all'):
        asyncio.run(audio(args.concurrency))
    if args.action in ('verify', 'all'):
        verify(args.decode)


if __name__ == '__main__':
    main()
